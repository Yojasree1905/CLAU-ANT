DATASET_DIR_NAME = {"sjt7": "sjt-7th-floor", "hblock3": "hblock-3rd-floor"}

for venue_id, nodes in REFERENCES.items():
    out = {}
    folder = DATASET_ROOT / DATASET_DIR_NAME[venue_id]
    for node_id, filenames in nodes.items():
        vectors = []
        for fn in filenames:
            p = folder / fn
            if not p.exists():
                print(f"WARNING missing {p}")
                continue
            vectors.append([round(x, 4) for x in fingerprint(p)])
        out[node_id] = vectors

    js_path = PROJECT_ROOT / "js" / "venues" / f"{DATASET_DIR_NAME[venue_id]}.fingerprints.js"
    js_path.write_text(
        "// Auto-generated by scripts/precompute_fingerprints.py — do not hand-edit.\n"
        "// Coarse 8x8 color-grid visual fingerprints for landmark recognition.\n"
        "// See localization.js for the matching algorithm and its limits.\n"
        f"window.registerFingerprints('{venue_id}', {json.dumps(out)});\n"
    )
    total_vecs = sum(len(v) for v in out.values())
    print(f"{venue_id}: {len(out)} nodes, {total_vecs} reference vectors -> {js_path}")
