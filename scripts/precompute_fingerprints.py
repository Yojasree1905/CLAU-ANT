"""
Precomputes a coarse visual fingerprint for a handful of reference photos
per landmark, using the exact same algorithm the browser will run on live
camera frames (js/localization.js): resize to 8x8, average RGB per cell,
normalize 0..1, flatten to a 192-length vector.

This is NOT a deep embedding (no neural net) — it's a classical low-res
color/layout descriptor, sometimes called a "tiny image" or block-color
fingerprint. It's cheap enough to run on any phone with zero model
download, but it only distinguishes scenes that look quite different in
overall color and layout (lift doors vs. a sofa vs. a stairwell) — it will
NOT reliably tell two similar-looking corridor segments apart. That
trade-off is documented in localization.js and the README.

Run once at build time; output is committed as js/venues/*.fingerprints.js
so the browser never has to touch Python or the raw dataset.
"""
import json
from pathlib import Path
from PIL import Image

GRID = 8
PROJECT_ROOT = Path(__file__).parent.parent
DATASET_ROOT = PROJECT_ROOT / "dataset"

def fingerprint(path):
    img = Image.open(path).convert("RGB")
    # Center-crop to square first so aspect ratio doesn't skew the grid,
    # matching what the runtime does with the camera frame.
    w, h = img.size
    side = min(w, h)
    left = (w - side) // 2
    top = (h - side) // 2
    img = img.crop((left, top, left + side, top + side)).resize((GRID, GRID), Image.BILINEAR)
    pixels = list(img.getdata())
    vec = []
    for (r, g, b) in pixels:
        vec.extend([r / 255.0, g / 255.0, b / 255.0])
    return vec

